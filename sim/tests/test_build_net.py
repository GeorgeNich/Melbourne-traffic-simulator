def test_osm_pass_options(tmp_path: Path):
    cmd = build_net.osm_pass_command(
        tmp_path / "x.osm.gz", tmp_path / "o.net.xml", tmp_path / "j.xml", tmp_path / "l.log"
    )
    for opt in (
        "--lefthand",
        "--output.original-names",
        "--geometry.remove",
        "--ramps.guess",
        "--roundabouts.guess",
        "--junctions.join",
        "--tls.guess-signals",
        "--no-turnarounds.tls",
    ):
        assert opt in cmd
    assert cmd[cmd.index("--keep-edges.by-vclass") + 1] == "passenger"
    assert cmd[cmd.index("--junctions.join-dist") + 1] == "15"
    assert "--tls.join" not in cmd  # see the build_net docstring for why
    assert "--tls.discard-simple" not in cmd  # mid-block signals stay traffic lights


def test_make_deterministic(tmp_path: Path):
    p = tmp_path / "n.net.xml"
    p.write_text('<?xml version="1.0"?>\n<!-- generated on 2026-10-26T23:35:55.79+10:00 by Eclipse')
    build_net.make_deterministic(p)
    assert p.read_text().endswith("<!-- generated by Eclipse")


@pytest.fixture
def grid_net(tmp_path: Path) -> Path:
    net = tmp_path / "grid.net.xml"
    subprocess.run(
        [
            sumolib.checkBinary("netgenerate"),
            "--grid",
            "--grid.number",
            "3",
            "--grid.length",
            "200",
            "--lefthand",
            "-o",
            str(net),
        ],
        check=True,
        capture_output=True,
    )
    return net


def test_patch_files_are_applied(tmp_path: Path, grid_net: Path, monkeypatch):
    net = sumolib.net.readNet(str(grid_net))
    edge = next(e for e in net.getEdges() if len(e.getOutgoing()) >= 2)
    target = next(iter(edge.getOutgoing()))
    patches = tmp_path / "patches"
    patches.mkdir()
    (patches / "test.con.xml").write_text(
        f'<connections>\n    <!-- test -->\n    <delete from="{edge.getID()}" '
        f'to="{target.getID()}"/>\n</connections>\n'
    )
    monkeypatch.setattr(build_net, "NET_PATCH_DIR", patches)
    out = tmp_path / "patched.net.xml"
    cmd = build_net.net_pass_command(grid_net, out, tmp_path / "patch.log")
    assert "--connection-files" in cmd
    build_net.run(cmd)
    patched = sumolib.net.readNet(str(out))
    assert target.getID() not in {t.getID() for t in patched.getEdge(edge.getID()).getOutgoing()}
    assert ET.parse(out).getroot().get("lefthand") == "true"


# --- the committed network ------------------------------------------------------------------

needs_net = pytest.mark.skipif(not NET_PATH.exists(), reason="sim/net/roads.net.xml not built")


@pytest.fixture(scope="module")
def net():
    return sumolib.net.readNet(str(NET_PATH), withPrograms=True)


@needs_net
def test_network_is_lefthand_and_deterministic_header():
    head = NET_PATH.read_text(encoding="utf-8")[:3000]
    assert "generated on" not in head
    root_tag = next(ET.iterparse(NET_PATH, events=("start",)))[1]
    assert root_tag.tag == "net"
    assert root_tag.get("lefthand") == "true"


@needs_net
def test_original_names_present(net):
    edges = net.getEdges()
    with_orig = [e for e in edges if e.getLanes()[0].getParam("origId")]
    assert len(with_orig) / len(edges) > 0.95


@needs_net
def test_cars_only_network(net):
    assert all(e.allows("passenger") for e in net.getEdges())
    assert not any(e.getType() == "highway.service" for e in net.getEdges())


@needs_net
def test_size_under_50_mb():
    assert NET_PATH.stat().st_size < 50e6
    assert JOINED_PATH.exists()


@needs_net
def test_generated_patches_applied(net):
    private = NET_PATCH_DIR / "private_roads.edg.xml"
    for d in ET.parse(private).getroot().iter("delete"):
        assert not net.hasEdge(d.get("id"))
    restr = NET_PATCH_DIR / "turn_restrictions.con.xml"
    for d in ET.parse(restr).getroot().iter("delete"):
        if net.hasEdge(d.get("from")):
            outgoing = {t.getID() for t in net.getEdge(d.get("from")).getOutgoing()}
            assert d.get("to") not in outgoing
    for c in ET.parse(restr).getroot().iter("connection"):
        outgoing = {t.getID() for t in net.getEdge(c.get("from")).getOutgoing()}
        assert c.get("to") in outgoing


@needs_net
def test_signal_timings_are_sumo_defaults(net):
    for tl in net.getTrafficLights():
        prog = next(iter(tl.getPrograms().values()))
        assert sum(p.duration for p in prog.getPhases()) == pytest.approx(90)
