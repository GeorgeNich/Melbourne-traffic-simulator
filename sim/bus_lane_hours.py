"""Bus-lane operating hours: which bus lanes are closed to cars at a given local time.

OSM carries no hours for any bus lane in the extract and no open dataset of bus-lane hours exists,
so the hours come from the City of Melbourne "Bus lanes" page:

    https://www.melbourne.vic.gov.au/bus-lanes   (read 2026-10-27)

That page is (c) City of Melbourne and NOT open-licensed. The rows in TABLE are single cited facts
(street, side, from-to cross streets, hours), not a dataset, used with George's approval of
2026-10-27 (PLAN.md decisions log; data/SOURCES.md references row "City of Melbourne, Bus lanes").

How it is applied (the same pattern as school zones in sim/conditional_speeds.py):

- The first netconvert pass closes every OSM bus lane to cars (sim/bus_lanes.py), so junction
  connections are built with the bus lanes in place and cars turn from the lanes they may use.
- `timed_lanes` matches each TABLE row with hours to those bus-only lanes BY GEOMETRY: the street
  name, the side of the street the lane lies on (the compass direction from the edge's car lanes
  to the bus lane), or for "inbound" the travel direction towards the Hoddle Grid centre, and the
  stretch between the two cross streets (the junctions where the street meets them).
- The second pass reopens the timed lanes to cars (sim/patches/net/timed_bus_lanes.edg.xml,
  generated by `write_patch`). Each reopened lane carries a `busLaneHours` lane param naming its
  TABLE row, so the network says which lanes a scenario clock closes again.
- The committed network is the BASELINE: its placeholder demand has no time of day or weekday, so
  no window can be said to contain it; timed lanes are open, always-on lanes closed.
- A scenario with a clock (Phase 3, e.g. the weekday AM peak) calls `bus_only_lanes(net, when)`
  and closes the returned timed lanes to cars (TraCI lane.setDisallowed) for the scenario.

Bus lanes not on the page (Victoria Pde, St Kilda Rd, Power St, Peel St, ...) and lanes the page
lists without hours (Spring St) stay closed at all times: a known issue, labelled in the road-rules
report. Public holidays are not known to a scenario: `bus_only_lanes` assumes an ordinary weekday.
"""

from __future__ import annotations

import math
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from sim.conditional_speeds import in_windows, parse_hours

SOURCE_URL = "https://www.melbourne.vic.gov.au/bus-lanes"
SOURCE_NOTE = (
    "City of Melbourne, 'Bus lanes' page (read 2026-10-27). (c) City of Melbourne, not "
    "open-licensed: operating hours used as cited facts only, approved by George 2026-10-27"
)
PARAM = "busLaneHours"


@dataclass(frozen=True)
class Entry:
    key: str
    street: str  # OSM name of the street
    side: str  # "north" / "south" / "east" / "west" side of the street, "inbound", "both"
    from_street: str  # cross streets bounding the stretch (OSM names)
    to_street: str
    hours: str | None  # opening-hours subset (sim.conditional_speeds.parse_hours); None: always


TABLE: tuple[Entry, ...] = (
    Entry(
        "queen_east",
        "Queen Street",
        "east",
        "Flinders Lane",
        "Lonsdale Street",
        "Mo-Fr 16:30-18:30",
    ),
    Entry(
        "lonsdale_north",
        "Lonsdale Street",
        "north",
        "Spencer Street",
        "Exhibition Street",
        "Mo-Fr 16:00-18:30",
    ),
    Entry(
        "lonsdale_south",
        "Lonsdale Street",
        "south",
        "Spencer Street",
        "Spring Street",
        "Mo-Fr 07:00-09:30",
    ),
    Entry(
        "city_rd_inbound",
        "City Road",
        "inbound",
        "Clarendon Street",
        "Queens Bridge Street",
        "Mo-Fr 06:30-10:00",
    ),
    # Listed on the page with no hours: always in force.
    Entry("spring_both", "Spring Street", "both", "Lonsdale Street", "Victoria Parade", None),
)
BY_KEY = {e.key: e for e in TABLE}

# A lane matches a row when at least this share of its edge lies between the cross streets, and
# the edge lies within LATERAL_M of the line joining them (same street, not a namesake elsewhere).
MIN_OVERLAP = 0.5
LATERAL_M = 60.0


@dataclass
class LaneMatch:
    key: str
    edge: str
    lane: int
    side_bearing: float  # compass bearing from the edge's car lanes to the bus lane
    side: str
    overlap: float  # share of the edge between the cross streets


def compass(bearing: float) -> str:
    return ("north", "east", "south", "west")[int(((bearing + 45) % 360) // 90)]


def _bearing(dx: float, dy: float) -> float:
    return math.degrees(math.atan2(dx, dy)) % 360


def _centroid(shape) -> tuple[float, float]:
    return sum(p[0] for p in shape) / len(shape), sum(p[1] for p in shape) / len(shape)


def is_bus_only(lane) -> bool:
    return lane.allows("bus") and not lane.allows("passenger")


def cross_nodes(net, street: str, cross: str) -> list:
    """Junctions where an edge named `street` meets an edge named `cross`."""
    out = []
    for n in net.getNodes():
        names = {e.getName() for e in (*n.getIncoming(), *n.getOutgoing())}
        if street in names and cross in names:
            out.append(n)
    return out


def side_bearing(edge, lane) -> float:
    """Compass bearing from the centroid of the edge's other lanes to `lane`."""
    others = [ln for ln in edge.getLanes() if ln.getIndex() != lane.getIndex()]
    x0, y0 = _centroid([p for ln in others for p in ln.getShape()])
    x1, y1 = _centroid(lane.getShape())
    return _bearing(x1 - x0, y1 - y0)


def _stretch(net, entry: Entry):
    """(origin, unit axis from->to, lo, hi) of the stretch between the cross streets."""
    a = cross_nodes(net, entry.street, entry.from_street)
    b = cross_nodes(net, entry.street, entry.to_street)
    if not a or not b:
        raise ValueError(
            f"{entry.key}: no junction of {entry.street} with "
            f"{entry.from_street if not a else entry.to_street}"
        )
    ax, ay = _centroid([n.getCoord() for n in a])
    bx, by = _centroid([n.getCoord() for n in b])
    d = math.hypot(bx - ax, by - ay)
    u = ((bx - ax) / d, (by - ay) / d)

    def s(p):
        return (p[0] - ax) * u[0] + (p[1] - ay) * u[1]

    lo = min(s(n.getCoord()) for n in a)
    hi = max(s(n.getCoord()) for n in b)
    return (ax, ay), u, lo, hi


def timed_lanes(net, cbd_centre: tuple[float, float], entries=TABLE) -> list[LaneMatch]:
    """Bus-only lanes of `net` matched to each TABLE row (see the module docstring).

    `cbd_centre` is the Hoddle Grid centre in network x/y (for "inbound")."""
    out = []
    for entry in entries:
        (ox, oy), u, lo, hi = _stretch(net, entry)
        for e in net.getEdges():
            if e.getName() != entry.street:
                continue
            fx, fy = e.getFromNode().getCoord()
            tx, ty = e.getToNode().getCoord()
            s1 = (fx - ox) * u[0] + (fy - oy) * u[1]
            s2 = (tx - ox) * u[0] + (ty - oy) * u[1]
            lat = max(abs((x - ox) * u[1] - (y - oy) * u[0]) for x, y in ((fx, fy), (tx, ty)))
            if lat > LATERAL_M:
                continue
            a, b = sorted((s1, s2))
            if b - a < 1e-6:
                overlap = 1.0 if lo <= a <= hi else 0.0
            else:
                overlap = max(0.0, min(b, hi) - max(a, lo)) / (b - a)
            if overlap < MIN_OVERLAP:
                continue
            if entry.side == "inbound":
                cx, cy = cbd_centre
                if math.hypot(tx - cx, ty - cy) >= math.hypot(fx - cx, fy - cy):
                    continue
            for ln in e.getLanes():
                if not is_bus_only(ln):
                    continue
                sb = side_bearing(e, ln)
                if entry.side not in ("inbound", "both") and compass(sb) != entry.side:
                    continue
                out.append(
                    LaneMatch(
                        entry.key,
                        e.getID(),
                        ln.getIndex(),
                        round(sb),
                        compass(sb),
                        round(overlap, 2),
                    )
                )
    return out


def hoddle_centre_xy(net, osm) -> tuple[float, float]:
    from sim.generated_patches import hoddle_grid

    corners = hoddle_grid(osm)
    lon = sum(c[0] for c in corners) / len(corners)
    lat = sum(c[1] for c in corners) / len(corners)
    return net.convertLonLat2XY(lon, lat)


def write_patch(net_path: Path, matches: list[LaneMatch], dst: Path) -> int:
    """Edge patch reopening the timed bus lanes (rows with hours) to cars: each gets the
    permissions of a car lane on the same edge and a `busLaneHours` param naming its row."""
    timed = [m for m in matches if BY_KEY[m.key].hours]
    want = {m.edge for m in timed}
    perms: dict[str, dict[int, dict[str, str]]] = {}
    for _, el in ET.iterparse(net_path):
        if el.tag == "edge" and el.get("id") in want:
            perms[el.get("id")] = {
                int(ln.get("index")): {k: ln.get(k) for k in ("allow", "disallow") if ln.get(k)}
                for ln in el.findall("lane")
            }
        if el.tag in ("edge", "connection"):
            el.clear()
    root = ET.Element("edges")
    root.append(ET.Comment(f" Generated by sim/bus_lane_hours.py. {SOURCE_NOTE}: {SOURCE_URL} "))
    for m in sorted(timed, key=lambda m: (m.edge, m.lane)):
        lanes = perms[m.edge]
        car = next(
            (
                a
                for i, a in sorted(lanes.items())
                if i != m.lane and "bus" not in a.get("allow", "")
            ),
            None,
        )
        if car is None:
            raise ValueError(f"{m.edge}: no car lane to copy permissions from")
        edge = ET.SubElement(root, "edge", {"id": m.edge})
        lane = ET.SubElement(edge, "lane", {"index": str(m.lane), **car})
        ET.SubElement(lane, "param", {"key": PARAM, "value": m.key})
    ET.indent(root)
    dst.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(root).write(dst, encoding="UTF-8", xml_declaration=True)
    return len(timed)


def active(entry: Entry, when: datetime | None) -> bool:
    """Is the row's bus lane in force at `when` (local time, ordinary weekday)? Rows without hours
    always are; with no clock (the baseline) timed rows are not."""
    if entry.hours is None:
        return True
    if when is None:
        return False
    windows, _, _ = parse_hours(entry.hours)
    return in_windows(windows, when)


def bus_only_lanes(net, when: datetime | None = None) -> dict[str, list[int]]:
    """{edge id: lane indices closed to cars} at local time `when` (None: the baseline, no clock).

    Always-on bus lanes are the network's bus-only lanes; timed ones are the lanes with a
    `busLaneHours` param whose row is in force at `when`."""
    out: dict[str, list[int]] = {}
    for e in net.getEdges():
        for ln in e.getLanes():
            key = ln.getParam(PARAM)
            closed = is_bus_only(ln) if key is None else active(BY_KEY[key], when)
            if closed:
                out.setdefault(e.getID(), []).append(ln.getIndex())
    return out


def timed_lane_rows(net) -> dict[str, list[str]]:
    """{row key: lane ids} of the timed bus lanes in a built network (from the lane params)."""
    out: dict[str, list[str]] = {}
    for e in net.getEdges():
        for ln in e.getLanes():
            key = ln.getParam(PARAM)
            if key is not None:
                out.setdefault(key, []).append(ln.getID())
    return out
