"""Build the SUMO network: data/processed/osm_sim_area.osm.gz -> sim/net/roads.net.xml.

Usage (from the repo root):
    uv run python -m sim.build_net
    uv run python -m sim.build_net --refresh-patches   # after the extract or options change

Two netconvert passes, so hand fixes can name the edge IDs of the finished network:

1. OSM import -> sim/work/roads_osm.net.xml, with the patches in sim/patches/osm/
   (*.typ.xml type overrides, *.nod.xml / *.edg.xml nodes and edges by OSM node id).
2. sim/work/roads_osm.net.xml + sim/patches/net/ (*.con.xml connection changes,
   *.tll.xml, *.edg.xml, *.nod.xml by network id) -> sim/net/roads.net.xml.
   private_roads.edg.xml and turn_restrictions.con.xml there are generated from the import
   (sim/generated_patches.py, sim/checks/restrictions.py); refresh them with --refresh-patches.

Options and why:
- --lefthand: Melbourne drives on the left.
- --output.original-names: every lane records its OSM way ids (param `origId`); edge ids also start
  with the way id ("123#2", "-123#0" for the reverse direction).
- --keep-edges.by-vclass passenger: cars only (Phase 2 decision). With SUMO's OSM typemap this
  drops highway=service (car-park aisles, driveways, laneways); the extract has no service=* subtag
  to tell them apart, and none of them should carry through traffic.
- --geometry.remove, --roundabouts.guess, --ramps.guess: standard OSM import clean-up.
- --junctions.join with --junctions.join-dist 15 (m): OSM maps most Melbourne arterials
  (St Kilda Rd, Kings Way, Flinders St, Spencer St, Wurundjeri Way, Footscray Rd) as two one-way
  carriageways, so one real intersection becomes 2-4 OSM nodes 10-25 m apart. Joining turns these
  into one junction with one signal program. Measured (placeholder demand, seed 42): at 10 m the
  heavy stress run has 14 teleports, at 15 m 1, at 20 m 0; but at 20 m one turn restriction can
  no longer be traced onto the network, while at 15 m all 285 are accounted for. Hence 15 m.
  Joining only clusters nodes linked by short edges, never nodes that merely lie close
  together, so a bridge over a road is not joined to it (the connectivity check verifies this).
- --tls.guess-signals: OSM puts highway=traffic_signals on the stop line of each approach, a few
  metres before the intersection; this moves those signals onto the intersection itself (one
  program per intersection). Signals on a plain stretch of road (mid-block pedestrian crossings)
  stay their own traffic lights (no --tls.discard-simple): SUMO gives them a 90 s cycle with a
  short red, so cars stop at the crossings as they do in the city.
- No --tls.join: it merged neighbouring signals (often a mid-block crossing with the next
  intersection) into one controller whose default program serves each group in turn, e.g. 11 s
  green per 90 s for Victoria St through traffic, and a 517 s cycle at the Montague St ramps.
  Without it, the heavy stress run drops from 8 teleports to 1.
- --no-turnarounds.tls: Victorian Road Rule 39 forbids U-turns at traffic lights unless signed.
- --junctions.left-before-right: equal-priority cross intersections. In SUMO's left-hand mode
  netconvert's default right_before_left is mirrored into give way to the LEFT; this option
  gives give way to the RIGHT, as Australian Road Rule 72 requires (sim/checks/road_rules.py
  tests it with TraCI).
- --osm.turn-lanes: use OSM turn:lanes arrows to choose which lane serves which turn.
- --osm.lane-access, on a copy of the extract whose bus lanes are rewritten as explicit bus:lanes
  tags (sim/work/osm_sim_area.bus_lanes.osm, sim/bus_lanes.py): bus lanes are closed to cars
  (ARR r.154-158), and netconvert builds every connection with them in place.
- Timed bus lanes: pass 2 reopens to cars the bus lanes whose City of Melbourne hours are part-time
  (sim/patches/net/timed_bus_lanes.edg.xml, generated by sim/bus_lane_hours.py). The network is the
  baseline (no clock); a scenario with a clock closes them again with bus_lane_hours.bus_only_lanes.
- CBD 40 km/h: untagged roads inside the Hoddle Grid get the City of Melbourne CBD area limit
  (sim/patches/net/cbd_speed_limit.edg.xml, generated; see generated_patches.cbd_area_speeds).
- --junctions.corner-detail 5: smoother corner shapes (visual only).
- After pass 2, left (kerb-side) turns at signals are made to follow their approach's phase
  (generated_patches.no_left_turn_on_red): with no pedestrians, netconvert's default programs
  leave them green in every phase, i.e. a left turn on red, which Australia does not allow.
- Signal timings in the network are SUMO's defaults (static, 90 s cycle style). Where the DTP
  signal sheets are verified (pipeline/reference/signal_sheets_verified.json), the real programs
  are written to sim/net/signals_real.add.xml (sim/signals_real.py, loaded at run time; phases
  without a car movement skipped) and the sheets' lane arrows are applied in pass 2
  (sim/lane_arrows.py, sheet_lane_*.xml patches).
"""

