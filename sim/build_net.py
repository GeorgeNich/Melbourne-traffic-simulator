# Options that affect connections, so both passes must agree on them.
SHARED_OPTIONS = [
    "--lefthand",
    "--output.original-names",
    "--output.street-names",
    "--no-turnarounds.tls",
    "--junctions.left-before-right",
    "--junctions.corner-detail",
    "5",
    "--seed",
    str(SEED),
    "--aggregate-warnings",
    "-1",
]


def _rel(p: Path) -> str:
    """Paths relative to the repo root, so the network header never records a home directory."""
    try:
        return str(p.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(p)


def patch_files(folder: Path, suffix: str) -> list[Path]:
    return sorted(folder.glob(f"*{suffix}")) if folder.is_dir() else []


def osm_pass_command(
    osm: Path,
    out: Path,
    joined: Path,
    log: Path,
    join_dist: float = JUNCTION_JOIN_DIST_M,
    skip: tuple[Path, ...] = (),
) -> list[str]:
    types = [SUMO_TYPEMAP, *patch_files(OSM_PATCH_DIR, ".typ.xml")]
    real = osm.resolve() == OSM_EXTRACT.resolve()
    # The real extract is imported through a copy with its bus lanes as explicit bus:lanes tags
    # (sim/bus_lanes.py); synthetic test inputs are imported as they are.
    osm_in = write_bus_lane_osm(osm, out.parent / BUS_LANE_OSM_NAME) if real else osm
    cmd = [
        "netconvert",
        "--osm-files",
        _rel(osm_in),
        "--type-files",
        ",".join(_rel(t) for t in types),
        "--keep-edges.by-vclass",
        "passenger",
        "--remove-edges.isolated",
        "--geometry.remove",
        "--roundabouts.guess",
        "--ramps.guess",
        "--junctions.join",
        "--junctions.join-dist",
        f"{join_dist:g}",
        "--junctions.join-exclude",
        ",".join(JOIN_EXCLUDE),
        "--junctions.join-output",
        _rel(joined),
        "--tls.guess-signals",
        "--osm.turn-lanes",
        "--osm.lane-access",
        *SHARED_OPTIONS,
        "--log",
        _rel(log),
        "-o",
        _rel(out),
    ]
    # Node and edge patches name OSM node ids of the real extract; other inputs (the synthetic
    # test networks) get the generic type defaults only.
    if real:
        nodes = [n for n in patch_files(OSM_PATCH_DIR, ".nod.xml") if n not in skip]
        if nodes:
            cmd += ["--node-files", ",".join(_rel(n) for n in nodes)]
        edges = patch_files(OSM_PATCH_DIR, ".edg.xml")
        if edges:
            cmd += ["--edge-files", ",".join(_rel(e) for e in edges)]
    keep = write_private_keep_list(osm, out.parent / (out.name + ".keep_private.txt"))
    if keep is not None:
        cmd += ["--geometry.remove.keep-edges.input-file", _rel(keep)]
    return cmd


BUS_LANE_OSM_NAME = "osm_sim_area.bus_lanes.osm"


def write_bus_lane_osm(osm: Path, dst: Path) -> Path:
    """The extract with its bus lanes as explicit bus:lanes tags (sim/bus_lanes.py)."""
    from sim import bus_lanes
    from sim.checks.netindex import read_osm

    bus_lanes.write_osm(osm, dst, bus_lanes.plan(read_osm(osm)))
    return dst


def write_private_keep_list(osm: Path, path: Path) -> Path | None:
    """Edge ids of private/permit ways, so --geometry.remove never merges them into a public edge
    (private_roads.edg.xml can then delete them whole). netconvert names OSM edges "<way>",
    "-<way>", "<way>#<k>" and "-<way>#<k>"; every candidate id is listed."""
    if not osm.exists():
        return None
    from sim.checks.netindex import read_osm
    from sim.generated_patches import PRIVATE_VALUES, motor_access

    ids = []
    for w, (refs, tags) in sorted(read_osm(osm).ways.items()):
        if motor_access(tags) in PRIVATE_VALUES:
            for sign in ("", "-"):
                ids.append(f"{sign}{w}")
                ids += [f"{sign}{w}#{k}" for k in range(len(refs))]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(ids) + "\n", encoding="utf-8")
    return path


# Lane arrows from the signal sheets (sim/lane_arrows.py): generated from the network built
# without them; the connection file goes last so its deletions see every other patch's result.
# local_knowledge_turns.con.xml (turn bans George confirmed) goes after even that, so the
# sheet arrows cannot re-add a banned connection.
SHEET_PATCHES = (
    "sheet_lane_arrows.con.xml",
    "sheet_lane_counts.edg.xml",
    "local_knowledge_turns.con.xml",
)


def net_pass_command(raw: Path, out: Path, log: Path, skip_sheets: bool = False) -> list[str]:
    cmd = ["netconvert", "--sumo-net-file", _rel(raw), *SHARED_OPTIONS]
    for opt, suffix in (
        ("--node-files", ".nod.xml"),
        ("--edge-files", ".edg.xml"),
        ("--connection-files", ".con.xml"),
        ("--tllogic-files", ".tll.xml"),
    ):
        files = [f for f in patch_files(NET_PATCH_DIR, suffix) if f.name not in SHEET_PATCHES]
        if not skip_sheets:
            sheets = [NET_PATCH_DIR / n for n in SHEET_PATCHES if n.endswith(suffix)]
            files += [f for f in sheets if f.exists()]
        if files:
            cmd += [opt, ",".join(_rel(f) for f in files)]
    cmd += ["--log", _rel(log), "-o", _rel(out)]
    return cmd


_GENERATED_ON = re.compile(r"<!-- generated on \S+ by ")


def make_deterministic(path: Path) -> None:
    """Drop the wall-clock timestamp from SUMO's header comment so rebuilds are byte-identical."""
    text = path.read_text(encoding="utf-8")
    path.write_text(_GENERATED_ON.sub("<!-- generated by ", text, count=1), encoding="utf-8")


def run(cmd: list[str]) -> None:
    binary = shutil.which(cmd[0]) or cmd[0]
    proc = subprocess.run(
        [binary, *cmd[1:]], cwd=REPO_ROOT, env=sumo_env(), capture_output=True, text=True
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        raise RuntimeError(f"{cmd[0]} failed with exit code {proc.returncode}")


def refresh_stop_lines(osm: Path, join_dist: float) -> None:
    """Rewrite sim/patches/osm/stop_line_signals.nod.xml from an import made without it.

    Needs the raw OSM download (crossing tags, which the extract does not keep); without it the
    committed file is left as it is."""
    from sim import generated_patches

    if not RAW_PBF.exists():
        print(f"{_rel(RAW_PBF)} missing: kept {_rel(STOP_LINE_PATCH)} as committed")
        return
    probe = WORK_DIR / "roads_osm_no_stop_lines.net.xml"
    run(
        osm_pass_command(
            osm,
            probe,
            WORK_DIR / "joined_probe.xml",
            WORK_DIR / "netconvert_probe.log",
            join_dist,
            skip=(STOP_LINE_PATCH,),
        )
    )
    rows = generated_patches.stop_line_signals(probe, RAW_PBF)
    generated_patches.write_stop_line_patch(rows, STOP_LINE_PATCH)
    print(f"rewrote {_rel(STOP_LINE_PATCH)}: {len(rows)} stop-line signals")


def refresh_generated_patches(osm_path: Path = OSM_EXTRACT) -> None:
    """Rewrite the generated patch files from the fresh OSM import (sim/generated_patches.py)."""
    import sumolib

    from sim import generated_patches
    from sim.checks import restrictions
    from sim.checks.netindex import NetIndex, read_joined, read_osm

    osm = read_osm(osm_path)
    idx = NetIndex(sumolib.net.readNet(str(RAW_NET)), read_joined(JOINED_PATH))
    private = generated_patches.private_edges(osm, idx)
    n = generated_patches.write_private_patch(private, osm, PRIVATE_PATCH)
    print(f"rewrote {_rel(PRIVATE_PATCH)}: {n} edge deletions")
    rows = restrictions.audit(RAW_NET, osm_path)
    n = restrictions.write_patch(rows, RESTRICTION_PATCH, skip_edges=set(private))
    print(f"rewrote {_rel(RESTRICTION_PATCH)}: {n} connection changes")
    from sim.checks.movements import Movements

    mv = Movements(osm, idx)
    rels, _ = restrictions.parse_restrictions(osm)
    local = restrictions.local_matchers(rels, osm, idx, mv)
    deleted = {(a, b) for r in rows if r.status == "violated" for a, b in r.offending}
    turns = generated_patches.missing_lane_turns(osm, idx, mv, local, deleted)
    turns = [t for t in turns if t.from_edge not in private and t.to_edge not in private]
    n = generated_patches.write_lane_patch(turns, LANE_PATCH)
    print(f"rewrote {_rel(LANE_PATCH)}: {n} lane connections on {len(turns)} approaches")
    rows = generated_patches.right_of_way_nodes(RAW_NET, osm, set(private))
    n = generated_patches.write_right_of_way_patch(rows, ROW_PATCH)
    print(f"rewrote {_rel(ROW_PATCH)}: {n} junction type changes")
    rows = generated_patches.give_way_priorities(RAW_NET, osm, set(private))
    n = generated_patches.write_give_way_patch(rows, GIVE_WAY_PATCH)
    print(f"rewrote {_rel(GIVE_WAY_PATCH)}: {n} edge priority changes")
    raw = sumolib.net.readNet(str(RAW_NET))
    rb_nodes = {
        n for _, nodes in generated_patches.osm_roundabouts(RAW_NET, osm, idx) for n in nodes
    }
    rows = generated_patches.t_intersection_priorities(raw, osm, set(private), rb_nodes)
    n = generated_patches.write_t_patch(rows, T_PATCH)
    print(f"rewrote {_rel(T_PATCH)}: {n} edge priority changes")
    rows = generated_patches.cbd_area_speeds(RAW_NET, osm, set(private))
    n = generated_patches.write_cbd_speed_patch(rows, CBD_SPEED_PATCH)
    print(f"rewrote {_rel(CBD_SPEED_PATCH)}: {n} edges at the CBD 40 km/h area limit")
    from sim import bus_lane_hours

    matches = bus_lane_hours.timed_lanes(raw, bus_lane_hours.hoddle_centre_xy(raw, osm))
    n = bus_lane_hours.write_patch(RAW_NET, matches, TIMED_BUS_PATCH)
    print(f"rewrote {_rel(TIMED_BUS_PATCH)}: {n} timed bus lanes open to cars in the baseline")


def build(
    osm: Path = OSM_EXTRACT,
    out: Path = NET_PATH,
    join_dist: float = JUNCTION_JOIN_DIST_M,
    refresh_patches: bool = False,
) -> dict[str, float]:
    if not osm.exists():
        raise FileNotFoundError(f"{osm} missing; it is written by data-engineer (pipeline.roads)")
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    out.parent.mkdir(parents=True, exist_ok=True)
    t0 = time.perf_counter()
    if refresh_patches:
        refresh_stop_lines(osm, join_dist)
    run(osm_pass_command(osm, RAW_NET, JOINED_PATH, LOG_OSM, join_dist))
    make_deterministic(JOINED_PATH)
    if refresh_patches:
        refresh_generated_patches(osm)
    from sim import lane_arrows, signals_real

    if refresh_patches and signals_real.SHEETS_PATH.exists():
        log = lane_arrows.refresh()
        print(f"rewrote sheet lane patches: {log['status']}, {log['edges']} lane counts")
    run(net_pass_command(RAW_NET, out, LOG_PATCH))
    make_deterministic(out)
    from sim.generated_patches import no_left_turn_on_red

    fixed = no_left_turn_on_red(out)
    print(
        f"signals: {fixed['left_turn_links_changed']} left-turn links in "
        f"{fixed['programs_changed']} programs no longer green on red"
    )
    if out == NET_PATH and signals_real.SHEETS_PATH.exists():
        log = signals_real.generate()
        print(f"wrote {_rel(signals_real.ADD_PATH)}: tiers {log['tiers']}")
    return {"seconds": time.perf_counter() - t0, "size_mb": out.stat().st_size / 1e6}


def summarise(net_path: Path = NET_PATH) -> str:
    import sumolib

    net = sumolib.net.readNet(str(net_path), withInternal=False)
    edges = net.getEdges()
    tls = net.getTrafficLights()
    lines = [
        f"edges: {len(edges)}",
        f"junctions: {len(net.getNodes())}",
        f"traffic lights: {len(tls)}",
        f"lane-km: {sum(e.getLength() * e.getLaneNumber() for e in edges) / 1000:.1f}",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--join-dist", type=float, default=JUNCTION_JOIN_DIST_M)
    ap.add_argument("-o", "--output", type=Path, default=NET_PATH)
    ap.add_argument(
        "--refresh-patches",
        action="store_true",
        help="regenerate the generated patches in sim/patches/net/ from the fresh OSM import "
        "(needed whenever the extract or the import options change edge ids)",
    )
    args = ap.parse_args(argv)
    stats = build(out=args.output, join_dist=args.join_dist, refresh_patches=args.refresh_patches)
    print(f"wrote {_rel(args.output)} ({stats['size_mb']:.1f} MB) in {stats['seconds']:.1f} s")
    print(summarise(args.output))
    print(f"logs: {_rel(LOG_OSM)}, {_rel(LOG_PATCH)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
