# --- CBD 40 km/h area limit (Hoddle Grid) ---------------------------------------------------

# The Hoddle Grid's corners: intersections of its four boundary streets (OSM names). At the
# north-east corner OSM ends Spring St just short of La Trobe St: the corner node is shared with
# Victoria Parade, which continues east from Spring St there.
HODDLE_CORNERS = (
    ("Flinders Street", ("Spencer Street",)),
    ("Flinders Street", ("Spring Street",)),
    ("La Trobe Street", ("Spring Street", "Victoria Parade")),
    ("La Trobe Street", ("Spencer Street",)),
)
CBD_LIMIT_MPS = round(40 / 3.6, 2)
NO_AREA_LIMIT_TYPES = ("highway.motorway", "highway.motorway_link", "highway.living_street")


def hoddle_grid(osm: OsmData) -> list[tuple[float, float]]:
    """(lon, lat) corners of the Hoddle Grid: the mean position of the OSM nodes shared by ways
    named after both streets of each corner (dual carriageways share several)."""
    by_name: dict[str, set[int]] = {}
    for _, (refs, tags) in osm.ways.items():
        if tags.get("name"):
            by_name.setdefault(tags["name"], set()).update(refs)
    corners = []
    for a, alternatives in HODDLE_CORNERS:
        shared: set[int] = set()
        for b in alternatives:
            shared = by_name.get(a, set()) & by_name.get(b, set())
            if shared:
                break
        if not shared:
            raise ValueError(f"no OSM node shared by {a} and {alternatives}: no Hoddle Grid")
        pts = [osm.nodes[n] for n in shared]
        corners.append((sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts)))
    return corners


def cbd_area_speeds(net_path: Path, osm: OsmData, gone: set[str]) -> list[dict]:
    """Edges that get the CBD 40 km/h area limit: inside the Hoddle Grid (midpoint inside the
    outline joining its four corner intersections), none of their OSM ways tagged maxspeed, and
    faster than
    40 km/h (the 50 km/h built-up default of urban_speed_defaults.typ.xml or SUMO's typemap).
    Signed limits (OSM maxspeed) always win; shared zones keep their 10 km/h; the outline streets
    themselves are left as tagged."""
    import sumolib
    from shapely.geometry import Point, Polygon

    net = sumolib.net.readNet(str(net_path))
    idx = NetIndex(net, [])
    grid = Polygon([net.convertLonLat2XY(lon, lat) for lon, lat in hoddle_grid(osm)])
    # the outline's own streets (and Victoria Parade at the north-east corner) keep their tags
    outline = {a for a, _ in HODDLE_CORNERS} | {b for _, bs in HODDLE_CORNERS for b in bs}
    rows = []
    for e in sorted(net.getEdges(), key=lambda x: x.getID()):
        if e.getID() in gone or e.getType() in NO_AREA_LIMIT_TYPES or e.getName() in outline:
            continue
        if e.getSpeed() <= CBD_LIMIT_MPS + 0.01:
            continue
        ways = [w for w in idx.ways_by_edge.get(e.getID(), []) if w in osm.ways]
        if not ways or any("maxspeed" in osm.ways[w][1] for w in ways):
            continue
        shape = e.getShape()
        mid = sumolib.geomhelper.positionAtShapeOffset(shape, e.getLength() / 2)
        if not grid.contains(Point(mid)):
            continue
        hw = sorted({osm.ways[w][1].get("highway", "?") for w in ways})
        rows.append(
            {
                "edge": e.getID(),
                "name": e.getName() or "",
                "ways": ways,
                "highway": hw,
                "from_kmh": round(e.getSpeed() * 3.6),
            }
        )
    return rows


CBD_SPEED_HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  PATCH: the CBD 40 km/h area speed limit on roads inside the Hoddle Grid that OSM leaves untagged.

  The City of Melbourne's Hoddle Grid (Flinders, Spring, La Trobe and Spencer Streets) has had a
  40 km/h area limit since the early 2010s (signed at the area's entries, not on each street).
  OSM tags most CBD streets with it, but some, mostly laneways and short pieces of street, carry
  no maxspeed, so the import gave them the 50 km/h built-up default (urban_speed_defaults.typ.xml).
  Every edge below lies inside the grid (its midpoint inside the outline joining the four corner
  intersections), has no maxspeed on any of its OSM ways, and is set to 40 km/h. Signed
  limits always win: lower tagged limits (e.g. 20 km/h little streets, 10 km/h shared zones) stay.
  A regulatory default, not a measurement.

  Generated by sim/generated_patches.py (cbd_area_speeds) from the unpatched import and the
  extract; regenerate with the build's refresh-patches option.
-->
<edges>
"""


def write_cbd_speed_patch(rows: list[dict], path: Path) -> int:
    lines = [CBD_SPEED_HEADER]
    for r in rows:
        note = (
            f"{r['name'] or 'unnamed'} ({'/'.join(r['highway'])}, OSM way(s) "
            f"{', '.join(map(str, r['ways']))}): {r['from_kmh']} -> 40 km/h"
        )
        lines.append(f"    <!-- {escape(note).replace('--', '-')} -->\n")
        lines.append(f'    <edge id="{r["edge"]}" speed="{CBD_LIMIT_MPS}"/>\n')
    lines.append("</edges>\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(lines), encoding="utf-8")
    return len(rows)
