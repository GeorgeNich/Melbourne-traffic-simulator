"""Patch files generated from the OSM extract and the unpatched import, then committed.

Written by `uv run python -m sim.build_net --refresh-patches` (edge ids change whenever the extract
or the import options change, so these are regenerated rather than hand-edited):

- sim/patches/net/private_roads.edg.xml: deletes edges whose OSM ways all restrict motor vehicles
  to private or permit holders (access/motor_vehicle/motorcar = private or permit). These are
  driveways and estate roads; with placeholder demand they would become rat-runs.
- sim/patches/net/turn_restrictions.con.xml: see sim/checks/restrictions.py.
- sim/patches/osm/stop_line_signals.nod.xml: OSM signal nodes that are the stop line of a
  signalised intersection but sit just beyond --tls.guess-signals' reach, so the import made them
  separate lights a few metres before the intersection (cars would stop twice). They become plain
  nodes; the intersection's own program controls the approach.
- sim/patches/net/turn_lanes.con.xml: turns that OSM lane arrows require but the import lacks.
  When every lane of a one-way approach points one way (e.g. turn:lanes=right|right), the approach
  must offer that turn. netconvert sometimes cannot apply the arrows, builds the opposite turn, and
  the restriction patch then deletes that (banned) turn, leaving a dead end. For each such
  approach this adds the connection to the road that a plausible, unrestricted OSM path through
  the junction reaches by turning that way.
- sim/patches/net/cbd_speed_limit.edg.xml: the CBD 40 km/h area limit on untagged roads inside
  the Hoddle Grid (cbd_area_speeds).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from xml.sax.saxutils import escape

from sim.checks.netindex import NetIndex, OsmData

# Same precedence as pipeline/roads.py: the most specific key present decides.
ACCESS_KEYS = ("motorcar", "motor_vehicle", "vehicle", "access")
PRIVATE_VALUES = {"private", "permit", "no"}


def motor_access(tags: dict[str, str]) -> str | None:
    for key in ACCESS_KEYS:
        if key in tags:
            return tags[key].strip().lower()
    return None


def private_edges(osm: OsmData, idx: NetIndex) -> dict[str, list[int]]:
    """{edge id: its OSM ways} for edges whose ways are all private/permit-only."""
    out = {}
    for eid, ways in idx.ways_by_edge.items():
        known = [w for w in ways if w in osm.ways]
        if known and all(motor_access(osm.ways[w][1]) in PRIVATE_VALUES for w in known):
            out[eid] = known
    return out


PRIVATE_HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  PATCH: remove roads that only private or permit holders may drive (OSM access, motor_vehicle or
  motorcar = private/permit). They are driveways and estate roads; with placeholder demand they
  would become rat-runs. Generated by sim/generated_patches.py from the unpatched import
  (sim/work/roads_osm.net.xml) and the extract; regenerate with the build's refresh-patches option.
-->
<edges>
"""


def write_private_patch(edges: dict[str, list[int]], osm: OsmData, path: Path) -> int:
    lines = [PRIVATE_HEADER]
    for eid in sorted(edges):
        ways = edges[eid]
        names = sorted({osm.way_name(w) for w in ways})
        access = sorted({motor_access(osm.ways[w][1]) or "" for w in ways})
        note = f"OSM way(s) {', '.join(map(str, ways))} ({'; '.join(names)}): {'/'.join(access)}"
        lines.append(f"    <!-- {escape(note).replace('--', '-')} -->\n")
        lines.append(f'    <delete id="{eid}"/>\n')
    lines.append("</edges>\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(lines), encoding="utf-8")
    return len(edges)


RIGHT_ARROWS = {"right", "slight_right", "sharp_right"}
LEFT_ARROWS = {"left", "slight_left", "sharp_left"}


def one_sided(tags: dict[str, str], key: str = "turn:lanes") -> str | None:
    """'right' / 'left' if every lane arrow under `key` points that way, else None.

    turn:lanes counts only on one-way ways; turn:lanes:forward/backward on two-way ways."""
    tl = tags.get(key)
    if not tl or (key == "turn:lanes" and tags.get("oneway") not in ("yes", "true", "1")):
        return None
    lanes = [set(x.split(";")) for x in tl.split("|")]
    for side, arrows in (("right", RIGHT_ARROWS), ("left", LEFT_ARROWS)):
        if all(lane and lane <= arrows for lane in lanes):
            return side
    return None


@dataclass
class LaneTurn:
    way: int
    name: str
    arrows: str
    from_edge: str
    to_edge: str
    to_name: str
    lanes: list[tuple[int, int]]
    turn_deg: float


def missing_lane_turns(osm: OsmData, idx: NetIndex, mv, local, deleted: set) -> list[LaneTurn]:
    """Approaches whose lane arrows show a turn the network does not offer (once the restriction
    deletions are applied), with the connection to add for each: all-one-side approaches that
    dead-end or offer only the opposite turn, and mixed approaches (e.g. left;through|through)
    with no connection at all in a direction their arrows show."""
    from sim.checks.movements import turn_angle
    from sim.checks.restrictions import _can_excuse

    out = []
    approaches = []  # (way, arrow key, side, junction at the end of travel, reverse direction?)
    for w, (refs, tags) in sorted(osm.ways.items()):
        if w not in idx.edges_by_way:
            continue
        for key, end, reverse in (
            ("turn:lanes", refs[-1], False),
            ("turn:lanes:forward", refs[-1], False),
            ("turn:lanes:backward", refs[0], True),
        ):
            side = one_sided(tags, key)
            if side is not None:
                approaches.append((w, key, side, idx.junction(end), reverse, None))
                continue
            # mixed arrows (e.g. left;through|through): every turn shown must be offered
            tl = tags.get(key)
            if not tl or (key == "turn:lanes" and tags.get("oneway") not in ("yes", "true", "1")):
                continue
            lanes = [set(x.split(";")) for x in tl.split("|")]
            for sd, arrows in (("right", RIGHT_ARROWS), ("left", LEFT_ARROWS)):
                marked = [i for i, ln in enumerate(lanes) if ln & arrows]
                if marked:
                    approaches.append(
                        (w, key, sd, idx.junction(end), reverse, (marked, len(lanes)))
                    )
    for w, key, side, jid, reverse, mixed in approaches:
        tags = osm.ways[w][1]
        want = {"r", "R"} if side == "right" else {"l", "L"}
        other = {"l", "L"} if side == "right" else {"r", "R"}
        for f in idx.edges_by_way[w]:
            if f.getToNode().getID() != jid or f.getID().startswith("-") != reverse:
                continue
            dirs = {
                c.getDirection()
                for t, cs in f.getOutgoing().items()
                if (f.getID(), t.getID()) not in deleted
                for c in cs
            }
            if mixed is not None:
                if dirs & want:
                    continue  # the turn the arrows show is offered
            elif dirs and not (dirs <= other and not dirs & want):
                continue  # it offers the turn, or goes straight (a gentle slip lane)
            best = None
            s_in = mv.in_seg(f)
            for t in f.getToNode().getOutgoing():
                s_out = mv.out_seg(t)
                if s_in is None or s_out is None or t.getID() in {f.getID()}:
                    continue
                members = mv.members.get(jid, set())
                for inner in mv.inner_paths(s_in.b, s_out.a, members):
                    path = [s_in, *inner, s_out]
                    if not _can_excuse(path, osm, mv):
                        continue
                    if any(m.violates(path) for m in local.get(jid, [])):
                        continue
                    turn = sum(
                        turn_angle(mv.xy[a.a], mv.xy[a.b], mv.xy[b.b])
                        for a, b in zip(path, path[1:], strict=False)
                    )
                    # Prefer the turn the arrows show; else straight on (e.g. a short stub that
                    # turns that way just beyond the junction). Never the opposite turn.
                    if (side == "right" and 30 <= turn <= 150) or (
                        side == "left" and -150 <= turn <= -30
                    ):
                        rank = 0
                    elif abs(turn) < 30 and mixed is None:
                        rank = 1
                    else:
                        continue
                    length = sum(mv._dist(x.a, x.b) for x in path)
                    if best is None or (rank, length) < best[0]:
                        best = ((rank, length), t, turn)
            if best is None:
                continue
            _, t, turn = best
            nf, nt = f.getLaneNumber(), t.getLaneNumber()
            # Left-hand traffic: lane 0 is at the kerb. Right turns go from and to the centre-most
            # lanes, left turns from and to the kerb lanes.
            # OSM lists lanes left to right, which is SUMO's lane order in a left-hand network.
            src = list(range(nf))
            if mixed is not None:
                marked, n_tag = mixed
                src = [i for i in marked if i < nf] if n_tag == nf else []
                if not src:
                    src = [0] if side == "left" else [nf - 1]
            if side == "right":
                lanes = [(i, max(0, min(nt - 1, nt - nf + i))) for i in src]
            else:
                lanes = [(i, min(k, nt - 1)) for k, i in enumerate(src)]
            out.append(
                LaneTurn(
                    w,
                    osm.way_name(w),
                    f"{key}={tags[key]}",
                    f.getID(),
                    t.getID(),
                    t.getName() or "",
                    lanes,
                    round(turn),
                )
            )
    return out


LANES_HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  PATCH: turns that OSM lane arrows require but the import lacks. Every lane of each approach below
  points one way (OSM turn:lanes), yet after the import and the restriction patch the approach
  offers no turn that way (netconvert could not apply the arrows and built the opposite, banned
  turn). Each <connection> adds the turn to the road a plausible, unrestricted OSM path through the
  junction reaches. Generated by sim/generated_patches.py; regenerate with the build's
  refresh-patches option.
-->
<connections>
"""


def write_lane_patch(turns: list[LaneTurn], path: Path) -> int:
    lines = [LANES_HEADER]
    n = 0
    for t in turns:
        note = (
            f"OSM way {t.way} ({t.name}, {t.arrows}) to {t.to_name or t.to_edge}, {t.turn_deg} deg"
        )
        lines.append(f"    <!-- {escape(note).replace('--', '-')} -->\n")
        for fl, tl in t.lanes:
            lines.append(
                f'    <connection from="{t.from_edge}" to="{t.to_edge}" '
                f'fromLane="{fl}" toLane="{tl}"/>\n'
            )
            n += 1
    lines.append("</connections>\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(lines), encoding="utf-8")
    return n


STOP_LINE_MAX_M = 45.0  # the approach edge from the signal to the intersection, at most


def stop_line_signals(net_path: Path, pbf: Path) -> list[dict]:
    """OSM traffic_signals nodes that the import made their own plain-road light, that are not a
    pedestrian crossing (no crossing tag in the raw data), and whose road leads within
    STOP_LINE_MAX_M straight into a signalised intersection: stop lines, not mid-block lights."""
    import osmium
    import sumolib

    from sim.checks.netindex import NetIndex, read_osm
    from sim.config import OSM_EXTRACT

    net = sumolib.net.readNet(str(net_path))
    # private roads are deleted later (private_roads.edg.xml): judge the junctions without them
    gone = set(private_edges(read_osm(OSM_EXTRACT), NetIndex(net, [])))

    def plain(node) -> bool:
        inc = [e for e in node.getIncoming() if e.getID() not in gone]
        out = [e for e in node.getOutgoing() if e.getID() not in gone]
        if len(inc) <= 1 and len(out) <= 1:
            return True
        if len(inc) == 2 and len(out) == 2:
            return {e.getFromNode().getID() for e in inc} == {e.getToNode().getID() for e in out}
        return False

    cands = {}
    for node in net.getNodes():
        is_light = node.getType().startswith("traffic_light")
        if is_light and plain(node) and node.getID().isdigit():
            cands[int(node.getID())] = node
    tags = {
        o.id: dict(o.tags) for o in osmium.FileProcessor(str(pbf), osmium.osm.NODE) if o.id in cands
    }
    rows = []
    for nid in sorted(cands):
        t = tags.get(nid, {})
        if t.get("highway") != "traffic_signals" or "crossing" in t:
            continue
        node = cands[nid]
        ahead = [
            e
            for e in node.getOutgoing()
            if e.getLength() <= STOP_LINE_MAX_M
            and e.getID() not in gone
            and e.getToNode().getType().startswith("traffic_light")
            and not plain(e.getToNode())
        ]
        if not ahead:
            continue
        e = min(ahead, key=lambda x: x.getLength())
        rows.append(
            {
                "node": nid,
                "road": e.getName() or "",
                "metres_to_intersection": round(e.getLength(), 1),
                "direction_tag": t.get("traffic_signals:direction") or t.get("direction"),
            }
        )
    return rows


STOP_LINE_HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  PATCH (OSM stage): stop-line signals that the import made into separate lights.

  OSM maps a signalised intersection with a highway=traffic_signals node on each approach's stop
  line. netconvert's tls.guess-signals folds such nodes into the intersection's program when
  they are within 25 m of it; the nodes below lie a little further out (or past a joined
  junction's edge), so the import gave each its own 90 s light a few metres before the
  intersection and cars stopped twice. Each is a stop line, not a mid-block crossing: no
  crossing tag in the raw OSM data (most carry traffic_signals:direction), and its road leads
  within 45 m straight into a signalised intersection, whose program then controls the
  approach. Here they become plain nodes.

  Generated by sim/generated_patches.py (stop_line_signals) from an import made without this file
  and the raw OSM node tags; regenerate with the build's refresh-patches option.
-->
<nodes>
"""


def write_stop_line_patch(rows: list[dict], path: Path) -> int:
    lines = [STOP_LINE_HEADER]
    for r in rows:
        note = f"{r['road']}: {r['metres_to_intersection']} m before the intersection" + (
            f", traffic_signals:direction={r['direction_tag']}" if r["direction_tag"] else ""
        )
        lines.append(f"    <!-- {escape(note).replace('--', '-')} -->\n")
        lines.append(f'    <node id="{r["node"]}" type="priority"/>\n')
    lines.append("</nodes>\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(lines), encoding="utf-8")
    return len(rows)


# --- right of way (Australian Road Rules) ---------------------------------------------------


def _legs(node, gone: set[str]) -> int:
    """Distinct neighbouring junctions (roads meeting here), private roads excluded."""
    return len(
        {e.getFromNode().getID() for e in node.getIncoming() if e.getID() not in gone}
        | {e.getToNode().getID() for e in node.getOutgoing() if e.getID() not in gone}
    )


def sign_approach(nid: int, osm: OsmData, idx: NetIndex, ways_at: dict[int, list[int]]):
    """(incoming edge, junction) a give_way / stop sign node belongs to: the edge carrying the
    sign's way that passes nearest the sign, and the junction it leads into. None if the sign's
    road is not in the network."""
    import math

    from shapely.geometry import LineString, Point

    ways = [w for w in ways_at.get(nid, []) if w in idx.edges_by_way]
    if not ways:
        return None
    p = Point(idx.xy(*osm.nodes[nid]))
    best = None
    for w in ways:
        for e in idx.edges_by_way[w]:
            d = LineString(e.getShape()).distance(p)
            # prefer the edge that ENDS near the sign (the approach), then the nearest
            to_end = math.dist(e.getShape()[-1], (p.x, p.y))
            key = (round(d, 1), to_end)
            if best is None or key < best[0]:
                best = (key, e)
    e = best[1]
    return e, e.getToNode()


def right_of_way_nodes(net_path: Path, osm: OsmData, gone: set[str]) -> list[dict]:
    """Junction type changes so the network follows the Australian Road Rules:

    - T-intersections (and two-road joints) that netconvert made equal-priority junctions become
      `priority`: the continuing road is major, the terminating road gives way (ARR r.69).
    - unsigned cross intersections of equal minor streets become left_before_right, which in
      SUMO's left-hand mode means give way to the vehicle on the right (r.72;
      sim/checks/road_rules.py tests it), also at 50 km/h where netconvert made them priority.
    - priority junctions with a stop-sign approach (OSM highway=stop) become `priority_stop`, so
      vehicles on minor links stop before entering (r.67); SUMO does not import stop signs.
    """
    import sumolib

    net = sumolib.net.readNet(str(net_path))
    idx = NetIndex(net, [])
    rows: dict[str, dict] = {}
    for node in net.getNodes():
        if node.getType() in ("left_before_right", "right_before_left") and _legs(node, gone) <= 3:
            rows[node.getID()] = {
                "node": node.getID(),
                "type": "priority",
                "why": f"{_legs(node, gone)}-road junction of equal roads: the terminating road "
                "gives way (r.69)",
            }
    ways_at: dict[int, list[int]] = {}
    for w, (refs, _) in osm.ways.items():
        for n in refs:
            ways_at.setdefault(n, []).append(w)
    for nid, tags in sorted(osm.node_tags.items()):
        if tags.get("highway") != "stop":
            continue
        found = sign_approach(nid, osm, idx, ways_at)
        if found is None:
            continue
        edge, junction = found
        jtype = rows.get(junction.getID(), {}).get("type", junction.getType())
        if jtype == "priority":
            rows[junction.getID()] = {
                "node": junction.getID(),
                "type": "priority_stop",
                "why": f"stop sign (OSM node {nid}) on the {edge.getName() or 'unnamed'} approach "
                "(r.67)",
            }
    for r in minor_cross_junctions(net, osm, gone):
        rows.setdefault(r["node"], r)
    return [rows[k] for k in sorted(rows)]


ROW_HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  PATCH: junction types for the Australian Road Rules (Victoria).

  - T-intersections that netconvert built as equal-priority junctions become `priority`, so the
    continuing road is major and the terminating road gives way (ARR rule 69).
  - Priority junctions with an OSM stop sign (highway=stop) on an approach become `priority_stop`,
    so vehicles on minor links stop before entering (rule 67). SUMO does not import stop signs.
  - Unsigned, unsignalised cross intersections of four equal minor streets become
    `left_before_right`, which in SUMO's left-hand mode is give way to the vehicle on the right
    (rule 72; sim/checks/road_rules.py tests it). netconvert only builds that type below its
    49 km/h threshold, so 50 km/h streets had become priority junctions.

  Generated by sim/generated_patches.py (right_of_way_nodes) from the unpatched import;
  regenerate with the build's refresh-patches option.
-->
<nodes>
"""


def write_right_of_way_patch(rows: list[dict], path: Path) -> int:
    lines = [ROW_HEADER]
    for r in rows:
        lines.append(f"    <!-- {escape(r['why']).replace('--', '-')} -->\n")
        lines.append(f'    <node id="{r["node"]}" type="{r["type"]}"/>\n')
    lines.append("</nodes>\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(lines), encoding="utf-8")
    return len(rows)


# --- signals: no left turn on red -----------------------------------------------------------

LEFT_DIRS = {"l", "L"}


def no_left_turn_on_red(net_path: Path) -> dict:
    """Rewrite the shipped network's signal programs so a left (kerb-side) turn is green only
    while the other movements of its approach are: Australia has no left turn on red (ARR
    r.56-57). netconvert's default programs leave a left turn green in every phase when, with no
    pedestrians simulated, nothing conflicts with it. Protected right-turn arrows are untouched.

    Per phase, a left-turn link that is green while its approach's through links (or, with no
    through movement, its other links) are all red or yellow takes their state (yellow if any
    is yellow, else red). Approaches with only left
    turns (signalised slip lanes) keep their program. Edits only the `state` strings in place,
    so the rest of the file is byte-identical. Returns counts."""
    import re
    import xml.etree.ElementTree as ET

    text = net_path.read_text(encoding="utf-8")
    root = ET.fromstring(text)
    by_tl: dict[str, list[tuple[int, str, str]]] = {}
    for c in root.iter("connection"):
        if c.get("tl") and c.get("linkIndex") is not None:
            by_tl.setdefault(c.get("tl"), []).append(
                (int(c.get("linkIndex")), c.get("dir"), c.get("from"))
            )
    changed_links = 0
    changed_programs = 0

    def fix_program(tl: str, states: list[str]) -> list[str]:
        nonlocal changed_links
        links = by_tl.get(tl, [])
        out = [list(s) for s in states]
        touched = set()
        for idx, d, frm in links:
            if d not in LEFT_DIRS:
                continue
            # a left turn follows its approach's through movement, else its other movements
            refs = [i for i, d2, f2 in links if f2 == frm and d2 == "s"] or [
                i for i, d2, f2 in links if f2 == frm and d2 not in LEFT_DIRS
            ]
            if not refs:
                continue
            for k, s in enumerate(states):
                if idx >= len(s) or s[idx] not in "Gg":
                    continue
                ref = {s[i] for i in refs if i < len(s)}
                if ref & set("Gg"):
                    continue
                out[k][idx] = "y" if "y" in ref else "r"
                touched.add(idx)
        changed_links += len(touched)
        return ["".join(s) for s in out]

    def repl(m: re.Match) -> str:
        nonlocal changed_programs
        block = m.group(0)
        tl = m.group(1)
        states = re.findall(r'state="([^"]*)"', block)
        new = fix_program(tl, states)
        if new == states:
            return block
        changed_programs += 1
        it = iter(new)
        return re.sub(r'state="[^"]*"', lambda _: f'state="{next(it)}"', block)

    new_text = re.sub(r'<tlLogic id="([^"]+)".*?</tlLogic>', repl, text, flags=re.S)
    net_path.write_text(new_text, encoding="utf-8")
    return {"programs_changed": changed_programs, "left_turn_links_changed": changed_links}


# --- signed approaches give way -------------------------------------------------------------


def osm_roundabouts(net_path: Path, osm: OsmData, idx: NetIndex) -> list[tuple[set, list]]:
    """(ring edges, nodes) of the network's roundabouts that OSM tags junction=roundabout /
    circular. --roundabouts.guess also marks some loops of one-way streets (e.g. in the CBD)
    that are not roundabouts; r.114 is applied only to the real ones."""
    import xml.etree.ElementTree as ET

    out = []
    for rb in ET.parse(net_path).getroot().iter("roundabout"):
        ring = set(rb.get("edges", "").split())
        tagged = any(
            osm.ways.get(w, ([], {}))[1].get("junction") in ("roundabout", "circular")
            for e in ring
            for w in idx.ways_by_edge.get(e, [])
        )
        if tagged:
            out.append((ring, rb.get("nodes", "").split()))
    return out


def give_way_priorities(net_path: Path, osm: OsmData, gone: set[str]) -> list[dict]:
    """Edge priorities so OSM give-way / stop signs and roundabout entries are minor approaches.

    netconvert chooses a priority junction's major road from edge priorities and geometry, so a
    signed side road sometimes ends up major. For each non-signalised junction with a signed
    approach, that road (the approach edge and the edge leaving the junction on the same OSM way)
    gets a priority one below every other road there; entries to OSM-tagged roundabouts likewise
    go below the circulating edges (ARR r.67-69, r.114)."""
    import sumolib

    net = sumolib.net.readNet(str(net_path))
    idx = NetIndex(net, [])
    ways_at: dict[int, list[int]] = {}
    for w, (refs, _) in osm.ways.items():
        for n in refs:
            ways_at.setdefault(n, []).append(w)
    rows: dict[str, dict] = {}

    def demote(edges: list, others: list, why: str) -> None:
        others = [e for e in others if e.getID() not in gone]
        if not others:
            return
        target = min(e.getPriority() for e in others) - 1
        for e in edges:
            if e.getID() in gone or e.getPriority() <= target:
                continue
            prev = rows.get(e.getID())
            if prev is None or target < prev["priority"]:
                rows[e.getID()] = {"edge": e.getID(), "priority": target, "why": why}

    for nid, tags in sorted(osm.node_tags.items()):
        kind = tags.get("highway")
        if kind not in ("give_way", "stop"):
            continue
        found = sign_approach(nid, osm, idx, ways_at)
        if found is None:
            continue
        edge, j = found
        if j.getType().startswith("traffic_light"):
            continue
        ways = set(idx.ways_by_edge.get(edge.getID(), []))
        signed = [edge] + [e for e in j.getOutgoing() if ways & set(idx.ways_by_edge[e.getID()])]
        others = [e for e in j.getIncoming() + j.getOutgoing() if e not in signed]
        demote(signed, others, f"{kind} sign (OSM node {nid}) on {edge.getName() or 'unnamed'}")

    for ring, nodes in osm_roundabouts(net_path, osm, idx):
        for nid in nodes:
            if not net.hasNode(nid):
                continue
            j = net.getNode(nid)
            entries = [e for e in j.getIncoming() if e.getID() not in ring]
            circ = [e for e in j.getIncoming() if e.getID() in ring]
            if entries and circ:
                demote(entries, circ, f"roundabout entry at {nid}")
    return [rows[k] for k in sorted(rows)]


