# --- r.69 / r.72 at unsigned, unsignalised minor-street junctions --------------------------

MINOR_TYPES = {
    "highway.residential",
    "highway.unclassified",
    "highway.living_street",
    "highway.tertiary",
}
UNSIGNALISED = {"priority", "priority_stop", "left_before_right", "right_before_left"}
SIGN_NEAR_M = 30.0
THROUGH_DEG = 160.0
MAX_ROUNDS = 200


def _arms(node, gone: set[str]) -> dict[str, list]:
    """Neighbouring junction -> [(is_outgoing, edge)]: one entry per road meeting here."""
    arms: dict[str, list] = {}
    for e in node.getOutgoing():
        if e.getID() not in gone:
            arms.setdefault(e.getToNode().getID(), []).append((True, e))
    for e in node.getIncoming():
        if e.getID() not in gone:
            arms.setdefault(e.getFromNode().getID(), []).append((False, e))
    return arms


def _arm_heading(outgoing: bool, edge) -> float:
    import math

    s = edge.getShape()
    a, b = (s[0], s[1]) if outgoing else (s[-1], s[-2])
    return math.degrees(math.atan2(b[1] - a[1], b[0] - a[0]))


def _signs_xy(osm: OsmData, net) -> list[tuple[float, float]]:
    return [
        net.convertLonLat2XY(*osm.nodes[n])
        for n, t in osm.node_tags.items()
        if t.get("highway") in ("stop", "give_way")
    ]


def _unsigned_minor(node, arms, signs) -> bool:
    import math

    if node.getType() not in UNSIGNALISED:
        return False
    if any(e.getType() not in MINOR_TYPES for lst in arms.values() for _, e in lst):
        return False
    x, y = node.getCoord()[:2]
    return not any(math.hypot(sx - x, sy - y) < SIGN_NEAR_M for sx, sy in signs)


def minor_cross_junctions(net, osm: OsmData, gone: set[str]) -> list[dict]:
    """Unsignalised junctions of four roads of one minor class with no stop / give-way sign
    within SIGN_NEAR_M: give way to the right (ARR r.72), i.e. left_before_right in SUMO's
    left-hand mode. netconvert only builds that below its 49 km/h speed threshold, so 50 km/h
    streets became priority junctions with an arbitrary major road."""
    signs = _signs_xy(osm, net)
    rows = []
    for node in net.getNodes():
        arms = _arms(node, gone)
        if len(arms) != 4 or not _unsigned_minor(node, arms, signs):
            continue
        if len({e.getType() for lst in arms.values() for _, e in lst}) != 1:
            continue
        rows.append(
            {
                "node": node.getID(),
                "type": "left_before_right",
                "why": "unsigned cross intersection of equal minor streets: give way to the "
                "right (r.72)",
            }
        )
    return rows


def t_intersection_priorities(
    net, osm: OsmData, gone: set[str], roundabout_nodes: set[str] | None = None
) -> list[dict]:
    """Edge priorities so the continuing road has right of way at unsigned, unsignalised
    minor-street T-intersections (ARR r.69): the terminating road's edges are set below the
    continuing road's. netconvert breaks ties between equal-class roads by speed, so an untagged
    50 km/h side street could beat a continuing street signed 40 km/h. Junctions with an OSM stop
    or give-way sign within SIGN_NEAR_M follow the sign instead (give_way_priorities), and
    nodes of OSM-tagged roundabouts follow r.114 (circulating traffic has priority)."""
    signs = _signs_xy(osm, net)
    prio = {e.getID(): e.getPriority() for e in net.getEdges()}
    ts = []
    for node in net.getNodes():
        if node.getID() in (roundabout_nodes or set()):
            continue
        arms = _arms(node, gone)
        if len(arms) != 3 or not _unsigned_minor(node, arms, signs):
            continue
        head = {nb: _arm_heading(*lst[0]) for nb, lst in arms.items()}
        nbs = list(arms)
        straight, pair = max(
            (abs((head[a] - head[b] + 180) % 360 - 180), (a, b))
            for i, a in enumerate(nbs)
            for b in nbs[i + 1 :]
        )
        if straight < THROUGH_DEG:
            continue  # a Y junction: no clear continuing road
        (stem,) = (nb for nb in nbs if nb not in pair)
        through = [e.getID() for nb in pair for _, e in arms[nb]]
        stem_edges = [e.getID() for _, e in arms[stem]]
        ts.append((node.getID(), through, stem_edges))
    why: dict[str, str] = {}
    for _ in range(MAX_ROUNDS):  # an edge can be a stem here and a continuing road elsewhere
        changed = False
        for jid, through, stem_edges in ts:
            target = min(prio[e] for e in through) - 1
            for e in stem_edges:
                if prio[e] > target:
                    prio[e] = target
                    why[e] = f"terminating road at T-intersection {jid} (r.69)"
                    changed = True
        if not changed:
            break
    else:
        print(f"t_intersection_priorities: no fixed point after {MAX_ROUNDS} rounds")
    orig = {e.getID(): e.getPriority() for e in net.getEdges()}
    return [
        {"edge": e, "priority": prio[e], "why": why[e]} for e in sorted(why) if prio[e] != orig[e]
    ]


